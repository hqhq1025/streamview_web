def _build_videos(channels: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    channel_lookup = {channel["channelId"]: channel for channel in channels}
    templates = _build_video_templates()
    videos: List[Dict[str, Any]] = []
    for index, template in enumerate(templates):
        channel = channel_lookup[template["channelId"]]
        days_ago = (index * 13) % 365
        upload_date = _iso_now_minus(timedelta(days=days_ago))
        youtube_id = YOUTUBE_VIDEO_IDS[index % len(YOUTUBE_VIDEO_IDS)]
        video_id = f"video-{index + 1}"
        videos.append(
            {
                "videoId": video_id,
                "title": template["title"],
                "description": (
                    f"This is an amazing video about {template['title'].lower()}. "
                    "Watch till the end for exclusive content!"
                ),
                "channelId": template["channelId"],
                "channelName": channel["name"],
                "channelAvatar": channel["avatar"],
                "thumbnail": f"https://img.youtube.com/vi/{youtube_id}/hqdefault.jpg",
                "duration": template["duration"],
                "uploadDate": upload_date,
                "viewCount": template["views"],
                "likeCount": int(template["views"] * 0.05),
                "dislikeCount": int(template["views"] * 0.001),
                "category": template["category"],
                "tags": [template["category"], "trending", "2024"],
                "youtubeId": youtube_id,
                "videoUrl": f"https://www.youtube.com/embed/{youtube_id}?rel=0",
                "watchUrl": f"https://www.youtube.com/watch?v={youtube_id}",
            }
        )
    return videos


